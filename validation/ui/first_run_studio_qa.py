"""Exercise the first-run studio offline, using only its fictional documents and simulated folders."""
from pathlib import Path
from tempfile import mkdtemp
from playwright.sync_api import sync_playwright, expect
from PIL import Image, ImageOps

entry = (Path(__file__).resolve().parents[2] / "docs/design/first-run-studio/index.html").as_uri()
out = Path(mkdtemp(prefix="first-run-studio-"))
errors = []
with sync_playwright() as pw:
    browser = pw.chromium.launch(channel="msedge", headless=True)
    for width, height in [(1240, 830), (375, 812)]:
        ctx = browser.new_context(viewport={"width": width, "height": height}, reduced_motion="reduce", offline=True)
        page = ctx.new_page()
        page.set_default_timeout(4000)
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.on("console", lambda m: errors.append(m.text) if m.type=="error" else None)
        for k, word in [("folio", "sage"), ("bench", "toast"), ("atlas", "Meridian")]:
            page.goto(entry + "#" + k, wait_until="networkidle")
            def loc(a, val=None):
                scope = page.locator("dialog[open]") if page.locator("dialog[open]").count() else page
                return scope.locator(f'[data-action="{a}"]'+(f'[data-value="{val}"]' if val is not None else "")).filter(visible=True)
            def press(a, v=None):
                loc(a,v).first.click()
            def sheet_text(t):
                expect(page.locator("dialog[open]")).to_contain_text(t)
            def read(t):
                expect(page.locator(".copy")).to_contain_text(t)
            def bounded():
                assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), (width,k,"overflow")
            expect(page).to_have_title("PristinePage · First-run studio")
            bounded()
            page.screenshot(path=str(out/f"first-run-{k}-{width}.png"), full_page=True)
            press("page","start")
            for key in ("fast","search","offline","yours","original"):
                press("ethos",key)
                expect(loc("ethos",key)).to_have_attribute("aria-pressed","true")
            press("view","Original")
            raw=page.locator(".art").inner_html()
            press("view","Corrected")
            assert page.locator(".art").inner_html()!=raw
            press("page","access")
            press("camera")
            sheet_text("Allow camera access?")
            press("gallery")
            read("Gallery and files only")
            press("page","languages")
            page.locator("#ui").select_option("Français")
            page.get_by_label("German",exact=True).check()
            expect(page.locator(".art")).to_contain_text("Bonjour")
            press("page","practice")
            expect(loc("acquire","Camera")).to_have_count(0)
            press("acquire","Files" if k=="atlas" else "Gallery")
            read("Scan · 24 Nov")
            press("compare","Original")
            original=page.locator(".art").inner_html()
            press("compare","Corrected")
            assert original!=page.locator(".art").inner_html()
            press("save")
            read("Saved. Come back to it.")
            press("edit")
            for tool in ["Frame","Flatten","Light","Color","Rotate"]:
                press("tool",tool)
                field=page.locator("#strength")
                field.press("Home")
                a=page.locator(".art").inner_html()
                field.press("End")
                assert a!=page.locator(".art").inner_html(),tool
            press("apply")
            press("edit")
            expect(loc("tool","Rotate")).to_have_attribute("aria-pressed","true")
            expect(page.locator("#strength")).to_have_value("100")
            press("compare","Original")
            assert page.locator(".art").inner_html()==original
            press("revert")
            press("apply")
            press("edit")
            read("All corrections are off")
            press("apply")
            press("search")
            page.locator("#query").fill("absent123")
            read("No matching pages")
            page.locator("#query").fill(word.upper())
            expect(page.locator("mark")).to_have_text(word,ignore_case=True)
            press("hit")
            read("Back at the worktable.")
            bounded()
            press("page","library")
            press("pick")
            press("folder","Documents / Field notes")
            sheet_text("Start an empty library")
            press("activate")
            read("Active: Documents / Field notes")
            press("operations")
            press("import")
            press("import-dialog","Backups / PristinePage")
            sheet_text("Confirm import")
            press("import-ok")
            sheet_text("The backup is unchanged")
            press("close")
            press("operations")
            press("export")
            press("export-ok")
            sheet_text("active library is unchanged")
            press("close")
            press("pick")
            press("folder","Scans / PristinePage")
            press("move-dialog")
            sheet_text("Only after the destination is verified")
            press("close")
            read("Active: Documents / Field notes")
            press("pick")
            press("folder","Scans / PristinePage")
            press("activate")
            read("Active: Scans / PristinePage")
            press("operations")
            press("import")
            press("import-dialog","Backups / PristinePage 1")
            sheet_text("Confirm copy and merge")
            press("import-ok")
            sheet_text("The backup is unchanged")
            press("close")
            press("default")
            press("move-dialog")
            press("move")
            sheet_text("retired the old library")
            press("close")
            press("page","access")
            press("camera")
            press("allow")
            read("Camera allowed")
            page.locator(".progress button").last.click()
            press("next")
            read("My scans")
            press("settings")
            read("English, German")
            page.reload(wait_until="networkidle")
            read("Français")
            press("replay")
            expect(page.locator(".progress button").first).to_have_attribute("aria-current","step")
            press("skip")
            read("My scans")
            press("practice-home")
            read("Saved. Come back to it.")
            bounded()
            press("fresh")
            press("page","practice")
            primary=page.locator(".stepfoot > .cta")
            for command, expected in [("Take sample photo","Ready to save."),("Save album","Saved. Come back to it."),("Reopen page","Back at the worktable."),("Apply","Saved. Come back to it."),("Try text search","Find it by a word.")]:
                expect(primary).to_contain_text(command)
                bounded()
                primary.click()
                read(expected)
            page.locator("#query").fill(word)
            expect(page.locator("mark")).to_have_text(word,ignore_case=True)
            press("page","languages")
            page.get_by_label("English",exact=True).uncheck()
            press("page","practice")
            read("No reading language selected")
            print(f"{k} {width}x{height}: capture/import, edit, original, revert, OCR, library operations, finish/skip/replay OK",flush=True)
        ctx.close()
    browser.close()
assert not errors, errors
for w in [1240,375]:
    images=[Image.open(out/f"first-run-{k}-{w}.png").convert("RGB") for k in ("folio","bench","atlas")]
    pane=420 if w==1240 else 260
    images=[ImageOps.contain(i,(pane,1200)) for i in images]
    sheet=Image.new("RGB",(sum(i.width for i in images),max(i.height for i in images)),"#e8ebe8")
    x=0
    for i in images:
        sheet.paste(i,(x,0))
        x+=i.width
    sheet.save(out/f"first-run-contact-{w}.png")
print("No browser errors. File-mode journeys completed with the browser offline.")
print(f"Review screenshots: {out}")
